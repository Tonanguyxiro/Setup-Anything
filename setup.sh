    local confirm
    while true; do
        tui_select \
            "${APP_NAME} — Remote Server Management" \
            "Status is read-only; install, update, and removal explicitly call sudo." \
            "Disk warning status (read-only)|Inspect installed files, timer state, and cached reports." \
            "Install detailed disk warning (root)|Install the scanner, login hook, configuration, and timer." \
            "Update detailed disk warning (root)|Refresh program files while preserving server configuration." \
            "Remove program, keep config (root)|Remove services and cache but retain /etc/disk-usage-warn.conf." \
            "Remove program and config (root)|Purge the program, service, cache, and configuration." \
            "Back|Return to the main menu."
        tui_clear
        case "$TUI_SELECTED" in
            0) run_disk_warning_action status; pause ;;
            1) run_disk_warning_action install; pause ;;
            2) run_disk_warning_action update; pause ;;
            3)
                read -r -p "Remove the disk warning program but keep its config? [y/N]: " confirm
                if [[ "$confirm" =~ ^[Yy]$ ]]; then
                    run_disk_warning_action remove
                else
                    printf 'Cancelled.\n'
                fi
                pause
                ;;
            4)
                read -r -p "Permanently remove the program, config, and cache? [y/N]: " confirm
                if [[ "$confirm" =~ ^[Yy]$ ]]; then
                    run_disk_warning_action purge
                else
                    printf 'Cancelled.\n'
                fi
                pause
                ;;
            5) return ;;
        esac
    done
}

