#!/usr/bin/env bash

set -euo pipefail

APP_NAME="Server Setup"
SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
TUI_LIBRARY="${SCRIPT_DIR}/tui/tui.sh"
[[ -r "$TUI_LIBRARY" ]] || { printf 'Error: missing TUI library: %s\n' "$TUI_LIBRARY" >&2; exit 1; }
# shellcheck disable=SC1090
source "$TUI_LIBRARY"
DISK_WARNING_INSTALLER="${SCRIPT_DIR}/02-Remote-Server-Management/disk-warning/disk-warning-detailed/install.sh"
ZSH_TEMPLATE="${SCRIPT_DIR}/01-Workspace/general/terminal/zsh/.zshrc"
OMZ_INSTALLER="${SCRIPT_DIR}/01-Workspace/general/terminal/zsh/install.sh"
TMUX_TEMPLATE="${SCRIPT_DIR}/01-Workspace/general/terminal/tmux/.tmux.conf"
MANAGED_HOME="${SERVER_SETUP_HOME:-$HOME}"
BASHRC_PATH="${SERVER_SETUP_BASHRC:-${MANAGED_HOME}/.bashrc}"
ZSHRC_PATH="${SERVER_SETUP_ZSHRC:-${MANAGED_HOME}/.zshrc}"
TMUX_CONF_PATH="${SERVER_SETUP_TMUX_CONF:-${MANAGED_HOME}/.tmux.conf}"
CONFIG_DIR="${MANAGED_HOME}/.config/server-setup"
BACKUP_DIR="${CONFIG_DIR}/backups"
SETTINGS_PATH="${CONFIG_DIR}/proxy-settings.sh"
CREDENTIALS_PATH="${CONFIG_DIR}/proxy-credentials.sh"
RUNTIME_PATH="${CONFIG_DIR}/proxy.sh"
ZSH_STATE_PATH="${CONFIG_DIR}/zsh-state"
ZSH_INSTALL_STATE_PATH="${CONFIG_DIR}/zsh-install-state"
ZSH_VERSION="5.9.2"
ZSH_PREFIX="${MANAGED_HOME}/.local/opt/zsh-${ZSH_VERSION}"
ZSH_BIN_LINK="${MANAGED_HOME}/.local/bin/zsh"
ZSH_SOURCE_URL="https://downloads.sourceforge.net/project/zsh/zsh/${ZSH_VERSION}/zsh-${ZSH_VERSION}.tar.xz"
BLOCK_START="# >>> Server-Setup automatic proxy >>>"
BLOCK_END="# <<< Server-Setup automatic proxy <<<"
LEGACY_BLOCK_PATTERN="# ===== Auto proxy config for local forwarded proxy ====="
TMUX_BLOCK_START="# >>> Server-Setup tmux configuration >>>"
TMUX_BLOCK_END="# <<< Server-Setup tmux configuration <<<"
ZSH_MANAGED_MARKER="# Managed by Server-Setup TUI"
ZSH_PATH_BLOCK_START="# >>> Server-Setup local Zsh PATH >>>"
ZSH_PATH_BLOCK_END="# <<< Server-Setup local Zsh PATH <<<"

die() {
    printf 'Error: %s\n' "$*" >&2
    exit 1
}

pause() {
    printf '\nPress Enter to continue...'
    read -r _
}

make_backup() {
    local source_path=$1 label=$2 timestamp destination
    [[ -e "$source_path" ]] || return 0
    mkdir -p "$BACKUP_DIR"
    chmod 700 "$CONFIG_DIR" "$BACKUP_DIR"
    timestamp=$(date '+%Y%m%d-%H%M%S')
    destination="${BACKUP_DIR}/${label}.${timestamp}"
    cp -p "$source_path" "$destination"
    chmod 600 "$destination"
    printf '%s' "$destination"
}

prompt() {
    local label=$1 default_value=$2 answer
    read -r -p "${label} [${default_value}]: " answer
    printf '%s' "${answer:-$default_value}"
}

validate_port() {
    local value=$1 name=$2
    [[ "$value" =~ ^[0-9]+$ ]] || die "${name} must be an integer"
    (( value >= 1 && value <= 65535 )) || die "${name} must be between 1 and 65535"
}

urlencode() {
    local value=$1 output="" char i
    LC_ALL=C
    for ((i = 0; i < ${#value}; i++)); do
        char=${value:i:1}
        case "$char" in
            [a-zA-Z0-9.~_-]) output+="$char" ;;
            *) printf -v char '%%%02X' "'$char"; output+="$char" ;;
        esac
    done
    printf '%s' "$output"
}

load_defaults() {
    PROXY_HOST="127.0.0.1"
    PROXY_PORT="20122"
    PROXY_SSH_HOST="A6000"
    PROXY_REMOTE_HOST="127.0.0.1"
    PROXY_REMOTE_PORT="43789"

    if [[ -r "$SETTINGS_PATH" ]]; then
        # This file is generated by this script and is writable only by the user.
        # shellcheck disable=SC1090
        source "$SETTINGS_PATH"
    fi
}

write_settings() {
    local proxy_host=$1 proxy_port=$2 ssh_host=$3 remote_host=$4 remote_port=$5

    mkdir -p "$CONFIG_DIR"
    chmod 700 "$CONFIG_DIR"
    {
        printf 'export PROXY_HOST=%q\n' "$proxy_host"
        printf 'export PROXY_PORT=%q\n' "$proxy_port"
        printf 'export PROXY_SSH_HOST=%q\n' "$ssh_host"
        printf 'export PROXY_REMOTE_HOST=%q\n' "$remote_host"
        printf 'export PROXY_REMOTE_PORT=%q\n' "$remote_port"
    } > "$SETTINGS_PATH"
    chmod 600 "$SETTINGS_PATH"
}

write_credentials() {
    local username=$1 password=$2 encoded_user encoded_password

    if [[ -z "$username" ]]; then
        rm -f "$CREDENTIALS_PATH"
        return
    fi

    encoded_user=$(urlencode "$username")
    encoded_password=$(urlencode "$password")
    printf 'export PROXY_AUTH=%q\n' "${encoded_user}:${encoded_password}" > "$CREDENTIALS_PATH"
    chmod 600 "$CREDENTIALS_PATH"
}

write_runtime() {
    local settings_quoted credentials_quoted
    printf -v settings_quoted '%q' "$SETTINGS_PATH"
    printf -v credentials_quoted '%q' "$CREDENTIALS_PATH"

    {
        printf '# Generated by %s/setup.sh. Do not store credentials in this file.\n' "$APP_NAME"
        printf 'source %s\n' "$settings_quoted"
        printf 'if [[ -r %s ]]; then\n    source %s\nfi\n' "$credentials_quoted" "$credentials_quoted"
        cat <<'EOF'

if [[ -n "${PROXY_AUTH:-}" ]]; then
    export PROXY_URL="http://${PROXY_AUTH}@${PROXY_HOST}:${PROXY_PORT}"
else
    export PROXY_URL="http://${PROXY_HOST}:${PROXY_PORT}"
fi

_server_setup_proxy_port_listening() {
    if command -v ss >/dev/null 2>&1; then
        ss -ltn "( sport = :${PROXY_PORT} )" 2>/dev/null | grep -q ":${PROXY_PORT}"
    elif command -v lsof >/dev/null 2>&1; then
        lsof -iTCP:"${PROXY_PORT}" -sTCP:LISTEN >/dev/null 2>&1
    else
        timeout 1 bash -c ":</dev/tcp/${PROXY_HOST}/${PROXY_PORT}" >/dev/null 2>&1
    fi
}

enable_proxy() {
    export HTTP_PROXY="${PROXY_URL}"
    export HTTPS_PROXY="${PROXY_URL}"
    export ALL_PROXY="${PROXY_URL}"
    export http_proxy="${PROXY_URL}"
    export https_proxy="${PROXY_URL}"
    export all_proxy="${PROXY_URL}"
    export NO_PROXY="localhost,127.0.0.1,::1"
    export no_proxy="${NO_PROXY}"
}

disable_proxy() {
    unset HTTP_PROXY HTTPS_PROXY ALL_PROXY
    unset http_proxy https_proxy all_proxy
    unset NO_PROXY no_proxy
}

auto_proxy() {
    if _server_setup_proxy_port_listening; then
        enable_proxy
    else
        disable_proxy
    fi
}

proxy_status() {
    printf 'Proxy port: %s:%s\n' "${PROXY_HOST}" "${PROXY_PORT}"
    if _server_setup_proxy_port_listening; then
        printf 'Port status: LISTENING\n'
    else
        printf 'Port status: NOT LISTENING\n'
    fi
    printf 'Authentication: %s\n' "$([[ -n "${PROXY_AUTH:-}" ]] && printf enabled || printf disabled)"
    printf 'HTTP_PROXY=%s\n' "${HTTP_PROXY:-<unset>}"
    printf 'HTTPS_PROXY=%s\n' "${HTTPS_PROXY:-<unset>}"
    printf 'ALL_PROXY=%s\n' "${ALL_PROXY:-<unset>}"
    printf 'NO_PROXY=%s\n' "${NO_PROXY:-<unset>}"
}

proxy_tunnel() {
    ssh -N -L "${PROXY_HOST}:${PROXY_PORT}:${PROXY_REMOTE_HOST}:${PROXY_REMOTE_PORT}" \
        "${PROXY_SSH_HOST}"
}

alias proxy-on='enable_proxy'
alias proxy-off='disable_proxy'
alias proxy-check='proxy_status'
alias proxy-tunnel='proxy_tunnel'

auto_proxy
EOF
    } > "$RUNTIME_PATH"
    chmod 600 "$RUNTIME_PATH"
}

strip_bashrc_block() {
    local source_path=$1 destination_path=$2
    awk -v start="$BLOCK_START" -v end="$BLOCK_END" '
        $0 == start { skipping = 1; next }
        $0 == end { skipping = 0; next }
        !skipping { print }
    ' "$source_path" > "$destination_path"
}

legacy_proxy_present() {
    [[ -f "$BASHRC_PATH" ]] && grep -Fq "$LEGACY_BLOCK_PATTERN" "$BASHRC_PATH"
}

remove_legacy_proxy_blocks() {
    local temp_path existing_mode
    [[ -f "$BASHRC_PATH" ]] || return 0
    existing_mode=$(stat -c '%a' "$BASHRC_PATH" 2>/dev/null || printf '600')
    temp_path=$(mktemp "${BASHRC_PATH}.tmp.XXXXXX")
    trap 'rm -f "${temp_path:-}"' RETURN
    awk -v marker="$LEGACY_BLOCK_PATTERN" '
        index($0, marker) && ($0 ~ /(START|BEGIN)$/) { skipping = 1; next }
        index($0, marker) && $0 ~ /END$/ { skipping = 0; next }
        !skipping { print }
    ' "$BASHRC_PATH" > "$temp_path"
    chmod "$existing_mode" "$temp_path"
    mv "$temp_path" "$BASHRC_PATH"
    trap - RETURN
}

migrate_legacy_proxy() {
    local answer backup_path
    legacy_proxy_present || return 0

    printf '\nA legacy automatic proxy block already exists in %s.\n' "$BASHRC_PATH"
    read -r -p "Back it up and replace it with the managed configuration? [Y/n]: " answer
    if [[ "$answer" =~ ^[Nn]$ ]]; then
        die "Configuration stopped to avoid duplicate proxy definitions"
    fi
    backup_path=$(make_backup "$BASHRC_PATH" "bashrc.before-proxy-migration")
    remove_legacy_proxy_blocks
    printf 'Legacy block removed. Backup: %s\n' "$backup_path"
}

update_bashrc() {
    local temp_path existing_mode

    mkdir -p "$(dirname "$BASHRC_PATH")"
    touch "$BASHRC_PATH"
    existing_mode=$(stat -c '%a' "$BASHRC_PATH" 2>/dev/null || printf '600')
    temp_path=$(mktemp "${BASHRC_PATH}.tmp.XXXXXX")
    trap 'rm -f "${temp_path:-}"' RETURN
    strip_bashrc_block "$BASHRC_PATH" "$temp_path"

    if [[ -s "$temp_path" ]] && [[ $(tail -c 1 "$temp_path" | wc -l) -eq 0 ]]; then
        printf '\n' >> "$temp_path"
    fi
    {
        printf '%s\n' "$BLOCK_START"
        printf 'if [[ -r %q ]]; then\n' "$RUNTIME_PATH"
        printf '    source %q\n' "$RUNTIME_PATH"
        printf 'fi\n'
        printf '%s\n' "$BLOCK_END"
    } >> "$temp_path"

    chmod "$existing_mode" "$temp_path"
    mv "$temp_path" "$BASHRC_PATH"
    trap - RETURN
}

remove_bashrc_block() {
    local temp_path existing_mode
    [[ -f "$BASHRC_PATH" ]] || return 0
    existing_mode=$(stat -c '%a' "$BASHRC_PATH" 2>/dev/null || printf '600')
    temp_path=$(mktemp "${BASHRC_PATH}.tmp.XXXXXX")
    trap 'rm -f "${temp_path:-}"' RETURN
    strip_bashrc_block "$BASHRC_PATH" "$temp_path"
    chmod "$existing_mode" "$temp_path"
    mv "$temp_path" "$BASHRC_PATH"
    trap - RETURN
}

configure_proxy() {
    local proxy_host proxy_port ssh_host remote_host remote_port use_auth username password
    load_defaults
    migrate_legacy_proxy

    printf '\nConfigure automatic proxy (no root required)\n\n'
    proxy_host=$(prompt "Local proxy host" "$PROXY_HOST")
    proxy_port=$(prompt "Local proxy port" "$PROXY_PORT")
    ssh_host=$(prompt "SSH host" "$PROXY_SSH_HOST")
    remote_host=$(prompt "Remote proxy host" "$PROXY_REMOTE_HOST")
    remote_port=$(prompt "Remote proxy port" "$PROXY_REMOTE_PORT")
    validate_port "$proxy_port" "Local proxy port"
    validate_port "$remote_port" "Remote proxy port"

    read -r -p "Enable proxy authentication? [y/N]: " use_auth
    username=""
    password=""
    if [[ "$use_auth" =~ ^[Yy]$ ]]; then
        read -r -p "Proxy username: " username
        [[ -n "$username" ]] || die "Proxy username cannot be empty"
        read -r -s -p "Proxy password: " password
        printf '\n'
        [[ -n "$password" ]] || die "Proxy password cannot be empty"
    fi

    write_settings "$proxy_host" "$proxy_port" "$ssh_host" "$remote_host" "$remote_port"
    write_credentials "$username" "$password"
    write_runtime
    update_bashrc

    printf '\nConfigured automatic proxy.\n'
    printf 'Bash entry: %s\n' "$BASHRC_PATH"
    printf 'Runtime:    %s\n' "$RUNTIME_PATH"
    printf 'Auth file:  %s\n' "$([[ -f "$CREDENTIALS_PATH" ]] && printf '%s' "$CREDENTIALS_PATH" || printf 'disabled')"
    printf 'Run: source %q\n' "$BASHRC_PATH"
}

remove_proxy() {
    remove_bashrc_block
    rm -f "$RUNTIME_PATH" "$SETTINGS_PATH" "$CREDENTIALS_PATH"
    rmdir "$CONFIG_DIR" 2>/dev/null || true
    printf 'Automatic proxy configuration removed.\n'
    printf 'Run: source %q\n' "$BASHRC_PATH"
}

show_status() {
    local bashrc_state="not configured" runtime_state="missing" auth_state="disabled"
    if [[ -f "$BASHRC_PATH" ]] && grep -Fqx "$BLOCK_START" "$BASHRC_PATH"; then
        bashrc_state="configured"
    fi
    [[ -r "$RUNTIME_PATH" ]] && runtime_state="installed"
    [[ -r "$CREDENTIALS_PATH" ]] && auth_state="enabled"

    printf '\nAutomatic proxy status\n'
    printf '  Bash entry:     %s (%s)\n' "$BASHRC_PATH" "$bashrc_state"
    printf '  Runtime:        %s (%s)\n' "$RUNTIME_PATH" "$runtime_state"
    printf '  Authentication: %s\n' "$auth_state"

    if [[ -r "$SETTINGS_PATH" ]]; then
        load_defaults
        printf '  Local endpoint: %s:%s\n' "$PROXY_HOST" "$PROXY_PORT"
        printf '  SSH tunnel:     %s -> %s:%s\n' "$PROXY_SSH_HOST" "$PROXY_REMOTE_HOST" "$PROXY_REMOTE_PORT"
    fi
}

strip_zsh_path_block() {
    local source_path=$1 destination_path=$2
    awk -v start="$ZSH_PATH_BLOCK_START" -v end="$ZSH_PATH_BLOCK_END" '
        $0 == start { skipping = 1; next }
        $0 == end { skipping = 0; next }
        !skipping { print }
    ' "$source_path" > "$destination_path"
}

rewrite_zsh_path_block() {
    local action=$1 temp_path existing_mode
    mkdir -p "$(dirname "$BASHRC_PATH")"
    touch "$BASHRC_PATH"
    existing_mode=$(stat -c '%a' "$BASHRC_PATH" 2>/dev/null || printf '600')
    temp_path=$(mktemp "${BASHRC_PATH}.tmp.XXXXXX")
    trap 'rm -f "${temp_path:-}"' RETURN
    strip_zsh_path_block "$BASHRC_PATH" "$temp_path"
    if [[ "$action" == install ]]; then
        if [[ -s "$temp_path" ]] && [[ $(tail -c 1 "$temp_path" | wc -l) -eq 0 ]]; then
            printf '\n' >> "$temp_path"
        fi
        {
            printf '%s\n' "$ZSH_PATH_BLOCK_START"
            printf 'export PATH="$HOME/.local/bin:$PATH"\n'
            printf '%s\n' "$ZSH_PATH_BLOCK_END"
        } >> "$temp_path"
    fi
    chmod "$existing_mode" "$temp_path"
    mv "$temp_path" "$BASHRC_PATH"
    trap - RETURN
}

download_file() {
    local url=$1 destination=$2
    if command -v curl >/dev/null 2>&1; then
        curl --fail --location --show-error --output "$destination" "$url"
    elif command -v wget >/dev/null 2>&1; then
        wget -O "$destination" "$url"
    else
        die "curl or wget is required to download Zsh"
    fi
}

install_zsh_from_source() {
    local build_dir archive jobs
    local required

    for required in make tar; do
        command -v "$required" >/dev/null 2>&1 || die "${required} is required to build Zsh"
    done
    if ! command -v cc >/dev/null 2>&1 && ! command -v gcc >/dev/null 2>&1; then
        die "A C compiler (cc or gcc) is required to build Zsh"
    fi
    [[ ! -e "$ZSH_BIN_LINK" ]] || die "Refusing to replace existing path: ${ZSH_BIN_LINK}"

    build_dir=$(mktemp -d /tmp/server-setup-zsh.XXXXXX)
    trap 'rm -rf "${build_dir:-}"' RETURN
    archive="${build_dir}/zsh-${ZSH_VERSION}.tar.xz"
    printf 'Downloading Zsh %s from the official SourceForge release...\n' "$ZSH_VERSION"
    download_file "$ZSH_SOURCE_URL" "$archive"
    tar -xJf "$archive" -C "$build_dir"

    jobs=$(getconf _NPROCESSORS_ONLN 2>/dev/null || printf '1')
    (
        cd "${build_dir}/zsh-${ZSH_VERSION}"
        ./configure --prefix="$ZSH_PREFIX"
        make -j"$jobs"
        make install
    )

    mkdir -p "$(dirname "$ZSH_BIN_LINK")" "$CONFIG_DIR"
    ln -s "${ZSH_PREFIX}/bin/zsh" "$ZSH_BIN_LINK"
    {
        printf 'version=%q\n' "$ZSH_VERSION"
        printf 'prefix=%q\n' "$ZSH_PREFIX"
        printf 'link=%q\n' "$ZSH_BIN_LINK"
    } > "$ZSH_INSTALL_STATE_PATH"
    chmod 600 "$ZSH_INSTALL_STATE_PATH"
    rewrite_zsh_path_block install
    export PATH="${MANAGED_HOME}/.local/bin:${PATH}"
    trap - RETURN
    rm -rf "$build_dir"
    printf 'Zsh installed without root: %s\n' "$ZSH_BIN_LINK"
}

ensure_zsh() {
    if command -v zsh >/dev/null 2>&1; then
        printf 'Using existing Zsh: %s\n' "$(command -v zsh)"
        return 0
    fi
    if [[ -x "$ZSH_BIN_LINK" ]]; then
        rewrite_zsh_path_block install
        export PATH="${MANAGED_HOME}/.local/bin:${PATH}"
        printf 'Using existing user-installed Zsh: %s\n' "$ZSH_BIN_LINK"
        return 0
    fi
    install_zsh_from_source
}

install_zsh_plugins() {
    local custom_dir plugin name url temporary_path
    command -v git >/dev/null 2>&1 || die "git is required to install Zsh plugins"
    custom_dir="${MANAGED_HOME}/.oh-my-zsh/custom/plugins"
    mkdir -p "$custom_dir"

    for plugin in \
        "zsh-autosuggestions|https://github.com/zsh-users/zsh-autosuggestions.git" \
        "zsh-syntax-highlighting|https://github.com/zsh-users/zsh-syntax-highlighting.git"; do
        name=${plugin%%|*}
        url=${plugin#*|}
        if [[ -d "${custom_dir}/${name}" ]]; then
            printf 'Using existing plugin: %s\n' "$name"
        else
            printf 'Installing plugin: %s\n' "$name"
            temporary_path="${custom_dir}/.${name}.server-setup.$$"
            [[ ! -e "$temporary_path" ]] || die "Temporary plugin path already exists: ${temporary_path}"
            if git clone --depth 1 "$url" "$temporary_path"; then
                mv "$temporary_path" "${custom_dir}/${name}"
            else
                rm -rf "$temporary_path"
                die "Failed to install plugin: ${name}"
            fi
        fi
    done
}

configure_zsh() {
    local backup_path
    [[ -f "$ZSH_TEMPLATE" ]] || die "Missing Zsh template: ${ZSH_TEMPLATE}"

    ensure_zsh

    mkdir -p "$CONFIG_DIR" "$BACKUP_DIR"
    chmod 700 "$CONFIG_DIR" "$BACKUP_DIR"
    if [[ ! -f "$ZSH_STATE_PATH" ]]; then
        if [[ -e "$ZSHRC_PATH" ]]; then
            backup_path=$(make_backup "$ZSHRC_PATH" "zshrc.before-server-setup")
            printf 'backup=%q\n' "$backup_path" > "$ZSH_STATE_PATH"
        else
            printf 'original_absent=1\n' > "$ZSH_STATE_PATH"
        fi
        chmod 600 "$ZSH_STATE_PATH"
    fi

    if [[ ! -f "${MANAGED_HOME}/.oh-my-zsh/oh-my-zsh.sh" ]]; then
        [[ -f "$OMZ_INSTALLER" ]] || die "Missing Oh My Zsh installer: ${OMZ_INSTALLER}"
        printf 'Oh My Zsh is missing; running the bundled unattended installer.\n'
        HOME="$MANAGED_HOME" ZSH="${MANAGED_HOME}/.oh-my-zsh" \
            RUNZSH=no CHSH=no KEEP_ZSHRC=yes sh "$OMZ_INSTALLER" --unattended
    fi
    install_zsh_plugins

    cp "$ZSH_TEMPLATE" "$ZSHRC_PATH"
    chmod 600 "$ZSHRC_PATH"
    printf 'Zsh configuration installed: %s\n' "$ZSHRC_PATH"
    printf 'Start it with: zsh\n'
}

remove_zsh() {
    local backup="" original_absent=0 changed_backup=""
    if [[ ! -f "$ZSH_STATE_PATH" ]]; then
        printf 'No TUI-managed Zsh configuration found.\n'
        return 0
    fi
    # This state file is generated by this script and writable only by the user.
    # shellcheck disable=SC1090
    source "$ZSH_STATE_PATH"

    if [[ -f "$ZSHRC_PATH" ]] && ! grep -Fqx "$ZSH_MANAGED_MARKER" "$ZSHRC_PATH"; then
        die "${ZSHRC_PATH} is no longer TUI-managed; refusing to overwrite it"
    fi
    if [[ -f "$ZSHRC_PATH" ]] && ! cmp -s "$ZSHRC_PATH" "$ZSH_TEMPLATE"; then
        changed_backup=$(make_backup "$ZSHRC_PATH" "zshrc.edited-before-restore")
    fi

    if [[ -n "$backup" && -f "$backup" ]]; then
        cp -p "$backup" "$ZSHRC_PATH"
        printf 'Original Zsh configuration restored: %s\n' "$ZSHRC_PATH"
    elif [[ "$original_absent" == 1 ]]; then
        rm -f "$ZSHRC_PATH"
        printf 'TUI-managed Zsh configuration removed.\n'
    else
        die "Zsh backup recorded in state is missing"
    fi
    rm -f "$ZSH_STATE_PATH"
    if [[ -f "$BASHRC_PATH" ]] && grep -Fqx "$ZSH_PATH_BLOCK_START" "$BASHRC_PATH"; then
        rewrite_zsh_path_block remove
    fi
    if [[ -f "$ZSH_INSTALL_STATE_PATH" ]]; then
        printf 'The TUI-installed Zsh binary was retained at: %s\n' "$ZSH_PREFIX"
    fi
    [[ -z "$changed_backup" ]] || printf 'Edited managed file saved as: %s\n' "$changed_backup"
    printf 'Oh My Zsh was retained because it may contain user plugins or themes.\n'
}

show_zsh_status() {
    local executable
    executable=$(command -v zsh 2>/dev/null || true)
    if [[ -z "$executable" && -x "$ZSH_BIN_LINK" ]]; then
        executable="${ZSH_BIN_LINK} (not in current PATH)"
    fi
    printf '\nZsh status\n'
    printf '  Executable:     %s\n' "${executable:-not found}"
    printf '  Oh My Zsh:      %s\n' "$([[ -f "${MANAGED_HOME}/.oh-my-zsh/oh-my-zsh.sh" ]] && printf installed || printf missing)"
    printf '  Configuration:  %s\n' "$([[ -f "$ZSH_STATE_PATH" ]] && printf TUI-managed || printf not-managed)"
    printf '  TUI installation:%s\n' "$([[ -f "$ZSH_INSTALL_STATE_PATH" ]] && printf ' yes (%s)' "$ZSH_PREFIX" || printf ' no')"
    printf '  Autosuggestions: %s\n' "$([[ -d "${MANAGED_HOME}/.oh-my-zsh/custom/plugins/zsh-autosuggestions" ]] && printf installed || printf missing)"
    printf '  Syntax highlight:%s\n' "$([[ -d "${MANAGED_HOME}/.oh-my-zsh/custom/plugins/zsh-syntax-highlighting" ]] && printf ' installed' || printf ' missing')"
    printf '  Target:         %s\n' "$ZSHRC_PATH"
}

