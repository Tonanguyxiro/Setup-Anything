run_disk_warning_action() {
    local action=$1
    [[ -x "$DISK_WARNING_INSTALLER" ]] || die "Missing installer: ${DISK_WARNING_INSTALLER}"

    case "$action" in
        status)
            "$DISK_WARNING_INSTALLER" --status
            ;;
        install)
            command -v sudo >/dev/null 2>&1 || die "sudo is required for server management"
            sudo "$DISK_WARNING_INSTALLER"
            ;;
        update)
            command -v sudo >/dev/null 2>&1 || die "sudo is required for server management"
            sudo "$DISK_WARNING_INSTALLER" --update
            ;;
        remove)
            command -v sudo >/dev/null 2>&1 || die "sudo is required for server management"
            sudo "$DISK_WARNING_INSTALLER" --remove
            ;;
        purge)
            command -v sudo >/dev/null 2>&1 || die "sudo is required for server management"
            sudo "$DISK_WARNING_INSTALLER" --remove --purge
            ;;
        *) die "Unknown disk warning action: ${action}" ;;
    esac
}

