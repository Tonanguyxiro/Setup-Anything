        fi
        {
            printf '%s\n' "$TMUX_BLOCK_START"
            printf 'source-file "%s"\n' "$TMUX_TEMPLATE"
            printf '%s\n' "$TMUX_BLOCK_END"
        } >> "$temp_path"
    fi

    chmod "$existing_mode" "$temp_path"
    mv "$temp_path" "$TMUX_CONF_PATH"
    trap - RETURN
}

configure_tmux() {
    command -v tmux >/dev/null 2>&1 || die "tmux is not installed or not available in PATH"
    [[ -f "$TMUX_TEMPLATE" ]] || die "Missing Tmux template: ${TMUX_TEMPLATE}"
    rewrite_tmux_config install
    if [[ -n "${TMUX:-}" ]]; then
        tmux source-file "$TMUX_CONF_PATH"
        printf 'Tmux configuration installed and reloaded: %s\n' "$TMUX_CONF_PATH"
    else
        printf 'Tmux configuration installed: %s\n' "$TMUX_CONF_PATH"
        printf 'It will load when the next Tmux server starts.\n'
    fi
}

remove_tmux() {
    if [[ ! -f "$TMUX_CONF_PATH" ]] || ! grep -Fqx "$TMUX_BLOCK_START" "$TMUX_CONF_PATH"; then
        printf 'No TUI-managed Tmux configuration found.\n'
        return 0
    fi
    rewrite_tmux_config remove
    printf 'TUI-managed Tmux configuration removed from: %s\n' "$TMUX_CONF_PATH"
    printf 'Restart Tmux to discard settings already loaded by the current server.\n'
}

show_tmux_status() {
    printf '\nTmux status\n'
    printf '  Executable:     %s\n' "$(command -v tmux 2>/dev/null || printf 'not found')"
    printf '  Configuration:  %s\n' "$([[ -f "$TMUX_CONF_PATH" ]] && grep -Fqx "$TMUX_BLOCK_START" "$TMUX_CONF_PATH" && printf TUI-managed || printf not-managed)"
    printf '  Target:         %s\n' "$TMUX_CONF_PATH"
    printf '  Template:       %s\n' "$TMUX_TEMPLATE"
}

