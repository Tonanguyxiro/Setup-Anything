usage() {
    cat <<EOF
Usage:
  ./setup.sh               Open the interactive setup menu
  ./setup.sh configure     Configure or update the proxy interactively
  ./setup.sh remove        Remove files and the managed ~/.bashrc block
  ./setup.sh status        Show managed configuration status
  ./setup.sh zsh configure|remove|status
                           Manage the user Zsh configuration
  ./setup.sh tmux configure|remove|status
                           Manage the user Tmux configuration
  ./setup.sh server status Show detailed disk warning status (read-only)
  ./setup.sh server install|update|remove|purge
                           Run a root-level disk warning action via sudo

Environment overrides for testing:
  SERVER_SETUP_HOME        Home directory to manage (default: \$HOME)
  SERVER_SETUP_BASHRC      Bash startup file to manage (default: ~/.bashrc)
EOF
}

case "${1:-menu}" in
    menu) interactive_menu ;;
    configure) configure_proxy ;;
    remove|unconfigure) remove_proxy ;;
    status) show_status ;;
    zsh)
        [[ $# -eq 2 ]] || { usage >&2; exit 2; }
        case "$2" in
            configure|install|update) configure_zsh ;;
            remove|unconfigure) remove_zsh ;;
            status) show_zsh_status ;;
            *) usage >&2; exit 2 ;;
        esac
        ;;
    tmux)
        [[ $# -eq 2 ]] || { usage >&2; exit 2; }
        case "$2" in
            configure|install|update) configure_tmux ;;
            remove|unconfigure) remove_tmux ;;
            status) show_tmux_status ;;
            *) usage >&2; exit 2 ;;
        esac
        ;;
    server)
        [[ $# -eq 2 ]] || { usage >&2; exit 2; }
        run_disk_warning_action "$2"
        ;;
    -h|--help|help) usage ;;
    *) usage >&2; exit 2 ;;
esac
